import type { Sector } from "@/types/occupation";
import type { InterestId, SkillId } from "@/data/taxonomy";

function s(
  id: string,
  name: string,
  description: string,
  subs: string[],
  activities: string[],
  interests: InterestId[],
  skills: SkillId[],
  environment: string,
  constraints: string[],
  misconceptions: string[],
): Sector {
  return {
    id,
    name,
    description,
    subsectors: subs.map((n) => ({
      id: `${id}--${n
        .toLowerCase()
        .normalize("NFD")
        .replace(/[̀-ͯ]/g, "")
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/(^-|-$)/g, "")}`,
      name: n,
    })),
    activities,
    interests,
    skills,
    environment,
    constraints,
    misconceptions,
    sourceReferences: [{ sourceId: "rome", note: "Domaines professionnels de référence" }, { sourceId: "editorial" }],
  };
}

